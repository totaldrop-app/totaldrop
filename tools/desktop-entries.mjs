// The Linux desktop entry and the file-manager menus, with their text in
// every language of l10n/app (#303). Their text lives in the ARB files
// like the rest of the app's (docs/ceviri.md); this writes it into the
// formats the desktops read.
//
//   node tools/desktop-entries.mjs write   Writes the files below.
//   node tools/desktop-entries.mjs check   Fails if any of them is not
//                                          what `write` would write (CI).
//
// Written:
//   packaging/linux/app.totaldrop.TotalDrop.desktop
//       The app's desktop entry, with "Send files" and "Receive files"
//       actions.
//   packaging/linux/file-managers/app.totaldrop.TotalDrop.send.desktop
//       Dolphin's right-click menu (a KIO service menu).
//   packaging/linux/file-managers/app.totaldrop.TotalDrop.nemo_action
//       Nemo's right-click menu.
//   packaging/linux/file-managers/totaldrop_nautilus.py
//       Only the block between its GENERATED lines: the menu text of the
//       hand-written Nautilus extension.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const l10nDir = join(root, "l10n/app");
const linux = join(root, "packaging/linux");
const fm = join(linux, "file-managers");

const ID = "app.totaldrop.TotalDrop";
const BEGIN = "# BEGIN GENERATED by tools/desktop-entries.mjs\n";
const END = "# END GENERATED\n";

// Words that find TotalDrop in every language: other apps people know for
// sending files. Not translated, added after each language's own words.
const EXTRA_KEYWORDS = ["wormhole", "localsend", "airdrop"];

/// ARB locale (`pt_BR`, `zh_Hans`) → the locales a desktop entry names it
/// by. The Desktop Entry Specification has no script subtag, so Chinese
/// scripts go by the regions that use them.
export function desktopLocales(arb) {
  switch (arb) {
    case "zh_Hans":
      return ["zh_CN", "zh_SG"];
    case "zh_Hant":
      return ["zh_TW", "zh_HK", "zh_MO"];
    default:
      if (!/^[a-z]{2,3}(_[A-Z]{2})?$/.test(arb)) {
        throw new Error(`no desktop locale for ARB locale ${arb}`);
      }
      return [arb];
  }
}

/// A text a translation may hold here: one line, no control characters,
/// no space at either end.
function checkText(text, where) {
  if (typeof text !== "string" || text === "") {
    throw new Error(`${where}: missing`);
  }
  // C0 and C1 controls, and the Unicode line and paragraph separators.
  if (/[\u0000-\u001f\u007f-\u009f\u2028\u2029]/u.test(text)) {
    throw new Error(`${where}: control character`);
  }
  if (text.trim() !== text) {
    throw new Error(`${where}: space at the start or end`);
  }
  return text;
}

/// A `string` or `localestring` value (Desktop Entry Specification,
/// "Possible value types"): `\` escaped first, then tab, carriage return
/// and newline (rejected above, escaped anyway), and a leading space.
export function escapeValue(text) {
  return text
    .replaceAll("\\", "\\\\")
    .replaceAll("\t", "\\t")
    .replaceAll("\r", "\\r")
    .replaceAll("\n", "\\n")
    .replace(/^ /, "\\s");
}

/// A list of `localestring`s: each item escaped, `;` inside an item as
/// `\;`, every item followed by `;`.
export function escapeList(items) {
  return items.map((i) => escapeValue(i).replaceAll(";", "\\;") + ";").join("");
}

/// The words of a `desktopKeywords` translation: split at `;`, trimmed,
/// empty ones dropped, each word once, then the extra words.
export function keywords(text, where) {
  const words = checkText(text, where)
    .split(";")
    .map((w) => w.trim())
    .filter((w) => w !== "");
  if (words.length === 0) throw new Error(`${where}: no words`);
  const out = [];
  for (const w of [...words, ...EXTRA_KEYWORDS]) {
    if (!out.includes(w)) out.push(w);
  }
  return out;
}

/// Every ARB file of l10n/app: locale → messages.
export function readCatalog(dir = l10nDir) {
  const out = new Map();
  for (const name of readdirSync(dir).sort()) {
    const m = /^app_(.+)\.arb$/.exec(name);
    if (!m) continue;
    const arb = JSON.parse(readFileSync(join(dir, name), "utf8"));
    if (arb["@@locale"] !== m[1]) {
      throw new Error(`${name}: @@locale is ${arb["@@locale"]}`);
    }
    out.set(m[1], arb);
  }
  if (!out.has("en")) throw new Error("no app_en.arb");
  return out;
}

/// `key[locale]=value` lines for every translation of `key` that a
/// desktop would not show anyway: one that differs from what the locale
/// falls back to, its language's base file (`pt_BR` → `pt`, `zh_CN` →
/// `zh`) or else English. Sorted by locale so the output does not depend
/// on the order of the files.
function localized(catalog, key, render) {
  const en = checkText(catalog.get("en")[key], `en: ${key}`);
  const lines = [];
  for (const [arb, messages] of catalog) {
    if (arb === "en") continue;
    const t = messages[key];
    if (t === undefined) continue; // untranslated: falls back to English
    checkText(t, `${arb}: ${key}`);
    for (const loc of desktopLocales(arb)) {
      const lang = loc.split("_")[0];
      const fallback = loc !== lang ? catalog.get(lang)?.[key] ?? en : en;
      if (t !== fallback) lines.push([loc, render(t, `${arb}: ${key}`)]);
    }
  }
  lines.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return lines;
}

function entryLines(catalog, field, key, render) {
  const en = catalog.get("en")[key];
  return [
    `${field}=${render(en, `en: ${key}`)}`,
    ...localized(catalog, key, render).map(([loc, v]) => `${field}[${loc}]=${v}`),
  ];
}

const text = (t) => escapeValue(t);
const words = (t, where) => escapeList(keywords(t, where));

// The generated files' own copyright lines; not this file's.
// REUSE-IgnoreStart
const HEADER =
  "# SPDX-FileCopyrightText: 2026 The TotalDrop Contributors\n" +
  "# SPDX-License-Identifier: GPL-3.0-or-later\n" +
  "#\n" +
  "# Written by tools/desktop-entries.mjs from l10n/app: change the text\n" +
  "# there and run `node tools/desktop-entries.mjs write`.\n";
// REUSE-IgnoreEnd

export function appEntry(catalog) {
  return [
    HEADER.trimEnd(),
    "[Desktop Entry]",
    "Type=Application",
    "Name=TotalDrop",
    ...entryLines(catalog, "GenericName", "desktopGenericName", text),
    ...entryLines(catalog, "Comment", "desktopComment", text),
    // %U: files come as file:// URLs, links (totaldrop://) as they are.
    "Exec=totaldrop-desktop %U",
    `Icon=${ID}`,
    "Terminal=false",
    "Categories=Network;FileTransfer;Qt;",
    ...entryLines(catalog, "Keywords", "desktopKeywords", words),
    // Only TotalDrop's own links. Every file type would make TotalDrop the
    // default opener of unknown files and folders where nothing else
    // claims them (a bare Hyprland); "Open With" lists it anyway (#303).
    "MimeType=x-scheme-handler/totaldrop;",
    "StartupNotify=true",
    `StartupWMClass=${ID}`,
    "SingleMainWindow=true",
    "Actions=send;receive;",
    "",
    "[Desktop Action send]",
    ...entryLines(catalog, "Name", "sendTitle", text),
    "Exec=totaldrop-desktop --screen=send",
    "",
    "[Desktop Action receive]",
    ...entryLines(catalog, "Name", "receiveTitle", text),
    "Exec=totaldrop-desktop --screen=receive",
    "",
  ].join("\n");
}

export function dolphinMenu(catalog) {
  return [
    HEADER.trimEnd(),
    "#",
    "# Dolphin's right-click menu (KIO service menu, KDE Frameworks 6), for",
    "# any selection of local files and folders.",
    "[Desktop Entry]",
    "Type=Service",
    "MimeType=all/all;",
    "X-KDE-Protocols=file",
    // On the menu itself, not under "Actions".
    "X-KDE-Priority=TopLevel",
    "Actions=send;",
    "",
    "[Desktop Action send]",
    ...entryLines(catalog, "Name", "desktopSendWith", text),
    `Icon=${ID}`,
    "Exec=totaldrop-desktop %U",
    "",
  ].join("\n");
}

export function nemoAction(catalog) {
  return [
    HEADER.trimEnd(),
    "#",
    "# Nemo's right-click menu, for any selection of local files and folders.",
    "# Nemo pastes the URIs into a command line that GLib splits like a shell,",
    "# and GLib leaves ' $ & ( ) raw in a file URI: each URI is quoted, and",
    "# no \" or \\ is left raw in one.",
    "[Nemo Action]",
    "Active=true",
    ...entryLines(catalog, "Name", "desktopSendWith", text),
    ...entryLines(catalog, "Comment", "desktopComment", text),
    "Exec=totaldrop-desktop %U",
    "Quote=double",
    `Icon-Name=${ID}`,
    "Selection=notnone",
    "UriScheme=file",
    "Extensions=any;",
    "Dependencies=totaldrop-desktop;",
    "",
  ].join("\n");
}

/// The GENERATED block of the Nautilus extension: the English label and a
/// dict of the others, keyed by the names GLib.get_language_names() gives.
export function nautilusBlock(catalog) {
  const key = "desktopSendWith";
  const en = checkText(catalog.get("en")[key], `en: ${key}`);
  const entries = [];
  for (const [arb, messages] of catalog) {
    if (arb === "en" || messages[key] === undefined) continue;
    const t = checkText(messages[key], `${arb}: ${key}`);
    for (const loc of desktopLocales(arb)) entries.push([loc, t]);
  }
  entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  // JSON string literals are Python string literals too.
  const lines = entries.map(([loc, t]) => `    ${JSON.stringify(loc)}: ${JSON.stringify(t)},`);
  return `${BEGIN}LABEL = ${JSON.stringify(en)}\nLABELS = {\n${lines.join("\n")}\n}\n${END}`;
}

export function withBlock(source, block) {
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start < 0 || end < start || source.indexOf(BEGIN, start + 1) >= 0) {
    throw new Error("the Nautilus extension needs exactly one GENERATED block");
  }
  return source.slice(0, start) + block + source.slice(end + END.length);
}

function outputs() {
  const catalog = readCatalog();
  const nautilus = join(fm, "totaldrop_nautilus.py");
  return [
    [join(linux, `${ID}.desktop`), appEntry(catalog)],
    [join(fm, `${ID}.send.desktop`), dolphinMenu(catalog)],
    [join(fm, `${ID}.nemo_action`), nemoAction(catalog)],
    [nautilus, withBlock(readFileSync(nautilus, "utf8"), nautilusBlock(catalog))],
  ];
}

function current(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

const cmd = process.argv[2];
if (cmd === "write") {
  for (const [path, content] of outputs()) {
    if (current(path) !== content) writeFileSync(path, content);
  }
} else if (cmd === "check") {
  const stale = outputs().filter(([path, content]) => current(path) !== content);
  for (const [path] of stale) {
    console.error(`${path.slice(root.length + 1)} is out of date: run node tools/desktop-entries.mjs write`);
  }
  if (stale.length) process.exit(1);
} else if (cmd !== undefined) {
  console.error("usage: desktop-entries.mjs write|check");
  process.exit(2);
}
