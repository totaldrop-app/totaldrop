// Writes android/app/src/main/res/values*/l10n.xml from the ARB files in
// l10n/app: the few texts Android shows itself, outside Flutter, such as
// the labels of the launcher shortcuts (#53). CI runs this and fails if a
// file in the repository is out of date.
//
//   dart run tool/gen_android_strings.dart
import 'dart:convert';
import 'dart:io';

/// Android string name → ARB key.
const strings = {
  'shortcut_send_short': 'homeSendTitle',
  'shortcut_send_long': 'sendTitle',
  'shortcut_receive_short': 'homeReceiveTitle',
  'shortcut_receive_long': 'receiveTitle',
};

const res = 'android/app/src/main/res';
const fileName = 'l10n.xml';

/// The resource folders for an ARB locale. Android has kept the old codes
/// for Hebrew (iw) and Indonesian (in) in places, so those get both.
List<String> folders(String arb) {
  if (arb == 'en') return ['values'];
  final parts = arb.split('_');
  if (parts.length == 2 && parts[1].length == 4) {
    return ['values-b+${parts[0]}+${parts[1]}']; // zh_Hans → b+zh+Hans
  }
  if (parts.length == 2) return ['values-${parts[0]}-r${parts[1]}'];
  return switch (arb) {
    'he' => ['values-he', 'values-iw'],
    'id' => ['values-id', 'values-in'],
    _ => ['values-$arb'],
  };
}

/// A string resource value: XML-escaped, then Android's own escapes for
/// quotes, backslashes and a leading @ or ?.
String escape(String s) {
  var out = s
      .replaceAll('\\', r'\\')
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', r'\"')
      .replaceAll("'", r"\'")
      .replaceAll('\n', r'\n');
  if (out.startsWith('@') || out.startsWith('?')) out = '\\$out';
  return out;
}

// The generated files' own copyright lines; not this file's.
// REUSE-IgnoreStart
String render(Map<String, String> values) {
  final b = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- SPDX-FileCopyrightText: 2026 The TotalDrop Contributors')
    ..writeln('     SPDX-License-Identifier: GPL-3.0-or-later')
    ..writeln()
    ..writeln(
      '     Generated by tool/gen_android_strings.dart from l10n/app. Do not edit. -->',
    )
    ..writeln('<resources>');
  for (final e in values.entries) {
    b.writeln('    <string name="${e.key}">${escape(e.value)}</string>');
  }
  b.writeln('</resources>');
  return b.toString();
}
// REUSE-IgnoreEnd

void main() {
  final written = <String>{};
  final files =
      Directory('../l10n/app')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.arb'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  for (final f in files) {
    final json = jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
    final locale = json['@@locale'] as String;
    final values = <String, String>{
      for (final e in strings.entries)
        if (json[e.value] case final String text) e.key: text,
    };
    if (values.isEmpty) continue;
    for (final folder in folders(locale)) {
      File('$res/$folder/$fileName')
        ..createSync(recursive: true)
        ..writeAsStringSync(render(values));
      written.add(folder);
    }
  }
  // A language that went away leaves no file behind.
  for (final d in Directory(res).listSync().whereType<Directory>()) {
    final name = d.uri.pathSegments.where((s) => s.isNotEmpty).last;
    final f = File('${d.path}/$fileName');
    if (f.existsSync() && !written.contains(name)) f.deleteSync();
  }
  stdout.writeln('$fileName: ${written.length} folders');
}
