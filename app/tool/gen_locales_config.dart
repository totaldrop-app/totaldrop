// Writes android/app/src/main/res/xml/locales_config.xml from the ARB files
// in l10n/app, so Android 13+ offers exactly the languages the app has in
// its per-app language settings (ADR 0008). CI runs this and fails if the
// file in the repository is out of date.
//
//   dart run tool/gen_locales_config.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final dir = Directory('../l10n/app');
  final tags = <String>{};
  for (final f in dir.listSync().whereType<File>()) {
    if (!f.path.endsWith('.arb')) continue;
    final json = jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
    final locale = json['@@locale'];
    if (locale is String) tags.add(locale.replaceAll('_', '-'));
  }
  final sorted = tags.toList()..sort();
  final out = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- Generated by tool/gen_locales_config.dart from l10n/app. Do not edit. -->')
    ..writeln('<locale-config xmlns:android="http://schemas.android.com/apk/res/android">');
  for (final t in sorted) {
    out.writeln('    <locale android:name="$t"/>');
  }
  out.writeln('</locale-config>');
  File('android/app/src/main/res/xml/locales_config.xml').writeAsStringSync(out.toString());
  stdout.writeln('locales_config.xml: ${sorted.join(', ')}');
}
