def label(language_names):
    """The menu text for the first of `language_names` (GLib's list, most
    specific first: tr_TR.UTF-8, tr_TR, tr.UTF-8, tr, C) that has one."""
    for name in language_names:
        if name in LABELS:
            return LABELS[name]
    return LABEL


def local_uris(files):
    """The file:// URIs of the selection, or None when any item is not a
    local file: the item is then not offered at all, rather than sending
    part of what was selected. An item in Recent (recent:///) stands for a
    local file, its activation URI."""
    uris = []
    for f in files:
        uri = f.get_activation_uri()
        if not uri or not uri.startswith("file://"):
            return None
        uris.append(uri)
    return uris or None


def _app_info():
    """TotalDrop's desktop entry, or None when it is not installed (or is
    hidden) for this session."""
    return Gio.DesktopAppInfo.new(APP_ID + ".desktop")


def launch(uris, context=None):
    """Open TotalDrop with `uris`. False when TotalDrop is not installed
    for this session or did not start; the reason goes to stderr, which
    Nautilus leaves in the journal (journalctl --user)."""
    info = _app_info()
    if info is None:
        print(f"TotalDrop: {APP_ID}.desktop was not found", file=sys.stderr)
        return False
    try:
        return info.launch_uris(uris, context)
    except GLib.Error as e:
        print(f"TotalDrop: could not start: {e}", file=sys.stderr)
        return False


def _launch_context():
    try:
        gi.require_version("Gdk", "4.0")
        from gi.repository import Gdk

        display = Gdk.Display.get_default()
        return display.get_app_launch_context() if display else None
    except (ValueError, ImportError):
        return None


class TotalDropMenu(GObject.GObject, Nautilus.MenuProvider):
    # API 4.0 (Nautilus 43 and later) passes only the selection.
    def get_file_items(self, files):
        uris = local_uris(files)
        # No menu when TotalDrop is not installed, as Nemo's Dependencies=.
        if uris is None or _app_info() is None:
            return []
        item = Nautilus.MenuItem(
            name="TotalDrop::send",
            label=label(GLib.get_language_names()),
        )
        item.connect("activate", lambda _item: launch(uris, _launch_context()))
        return [item]
