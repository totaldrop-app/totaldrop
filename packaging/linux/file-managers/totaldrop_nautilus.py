# also Omarchy's file manager), for one or more selected files and folders
# (#303). Nautilus loads this file through nautilus-python from
# /usr/share/nautilus-python/extensions/.
#
# The selection goes to TotalDrop the way "Open With" sends it: through the
# desktop entry, as file:// URIs, with Nautilus's launch context. So a file
# name with spaces, quotes or a leading "-" reaches the app unchanged, no
# shell is involved, and on Wayland the window may come to the front. A
# running TotalDrop takes the files into its open window (one window per
# session, linux/src/instance.rs). Only local files are offered: TotalDrop
# reads from disk, not from network locations.
#
# The menu text comes from l10n/app (desktopSendWith); the block between
# the GENERATED lines is written by `node tools/desktop-entries.mjs write`.

